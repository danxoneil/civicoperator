/**
 * Markdown content negotiation for www.civicoperator.com
 * ------------------------------------------------------
 * The site is static (GitHub Pages) and can't branch on request headers, so
 * this Worker sits in front of the origin and implements the "Markdown for
 * Agents" behavior from Cloudflare's Agent Readiness rubric:
 *
 *   - A request whose `Accept` header includes `text/markdown` gets the clean
 *     Markdown companion (e.g. /work/rht/states/texas/index.md) returned AT THE
 *     SAME canonical URL, with `Content-Type: text/markdown`.
 *   - Browsers (Accept: text/html) get the normal HTML, unchanged.
 *   - HTML responses also advertise the Markdown alternate via a `Link` header
 *     so agents can discover it.
 *
 * The .md companions are generated by scripts/generate_markdown.py and served
 * by the origin, so this Worker never changes when content changes.
 *
 * Deploy: see worker/README.md (one-time paste in the Cloudflare dashboard).
 */

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const accept = request.headers.get("Accept") || "";
    const wantsMarkdown = /\btext\/markdown\b/i.test(accept);
    const mdPath = markdownPathFor(url.pathname);

    // 1) Agent asked for Markdown and this URL has a companion -> serve it.
    if (wantsMarkdown && mdPath) {
      const mdUrl = new URL(request.url);
      mdUrl.pathname = mdPath;
      const md = await fetch(mdUrl, { headers: { Accept: "text/plain" } });
      if (md.ok) {
        const headers = new Headers(md.headers);
        headers.set("Content-Type", "text/markdown; charset=utf-8");
        headers.set("Vary", "Accept");
        headers.set("X-Markdown-Negotiation", "hit");
        return new Response(md.body, { status: 200, headers });
      }
      // Fall through to HTML if the companion is missing for some reason.
    }

    // 2) Otherwise pass through to origin.
    const response = await fetch(request);

    // Advertise the Markdown alternate on HTML pages that have a companion.
    const type = response.headers.get("Content-Type") || "";
    if (mdPath && type.includes("text/html")) {
      const headers = new Headers(response.headers);
      const abs = new URL(mdPath, url.origin).toString();
      headers.append("Link", `<${abs}>; rel="alternate"; type="text/markdown"`);
      headers.set("Vary", "Accept");
      return new Response(response.body, {
        status: response.status,
        statusText: response.statusText,
        headers,
      });
    }
    return response;
  },
};

/**
 * Map a page URL to its Markdown companion path, or null if this URL is not a
 * negotiable page (assets, .md files themselves, robots.txt, sitemap.xml, ...).
 */
function markdownPathFor(pathname) {
  if (pathname.endsWith(".md")) return null;         // the companion itself
  if (pathname === "/") return "/index.md";
  if (pathname.endsWith("/")) return pathname + "index.md";
  if (pathname.endsWith(".html")) return pathname.slice(0, -5) + ".md";
  if (!/\.[a-z0-9]+$/i.test(pathname)) return pathname + "/index.md"; // extensionless
  return null;                                        // .css/.png/.xml/.txt/.ico/...
}
